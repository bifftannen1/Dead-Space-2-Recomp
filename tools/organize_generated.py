r"""organize_generated.py -- rewrite app/generated into a named tree that mirrors the original
game's source layout, without changing a single function body.

    python tools/organize_generated.py                 # write/refresh app/generated_named
    python tools/organize_generated.py --verify        # (a) exactly-once + set equality,
                                                       # (b) every body byte-identical, (d) idempotence

What it does
  * Reads every DEFINE_REX_FUNC block from app/generated/ds2_rex_diagnostic_recomp.*.cpp.
    A recomp file must hold only #include lines, blank lines and whole blocks; anything else
    is a refusal (exit 2), never a guess.
  * Places each block in app/generated_named/<tree_path> from config/allocation.tsv.gz
    (tools/naming/build_allocation.py; one row per registered address). Inside a file blocks
    are in address order; a file over --max-per-file blocks is split into <file>.partN.cpp.
  * Each TU: the PCH include, DECLARE_REX_FUNC for exactly the codegen-declared symbols its
    text references, then per function a comment (address, PDB name, class, source line,
    prototype, CV calling convention) and `#define <ident> <symbol>` -- an alias, so the symbol,
    DEFINE_REX_FUNC and registration by address are all unchanged.
  * --ids pdb (default): every named, defined function's sub_<ADDR> (and __imp__sub_<ADDR>) is
    rewritten to its PDB-derived identifier in definitions, calls, the unit declaration headers
    (_units/<project>_funcs.N.h), the full surface (<project>_funcs.h, _init.h) and the
    registration/mapping tables (<project>_register.cpp, _init.cpp), which are then compiled
    from this tree. Scheme in build_rename() and docs/NAMED_TREE.md. No #define aliases are
    emitted; ds2_names.h lists the map and symbols.tsv is the machine-readable map
    (compare_objs_exact.py --name-map, organizer --verify). Unnamed functions keep sub_<ADDR>,
    loc_ labels are untouched, registration stays by address.
    --ids sub: the previous behaviour (symbols unchanged, `#define <ident> <symbol>` aliases).
  * Writes ds2_names.h (every alias), sources.cmake (GENERATED_SOURCES: init.cpp and
    register.cpp from app/generated, then the named TUs), manifest.tsv, source.fingerprint.
  * Writes a file only when its bytes change and deletes files it no longer owns; prints the
    count. A second run must print "0 files changed".

The named tree holds game-derived code and names: app/generated_named/ is gitignored.
"""
from __future__ import annotations

import argparse, collections, csv, gzip, hashlib, json, re, sys
from pathlib import Path

csv.field_size_limit(1 << 30)
REPO = Path(__file__).resolve().parents[1]
APP = REPO / "app"
PROJECT = "ds2_rex_diagnostic"
BEGIN = re.compile(r"^DEFINE_REX_FUNC\((\w+)\) \{$")
DECL = re.compile(r"^DECLARE_REX_FUNC\((\w+)\);$")
# codegen's own rule for a TU's declaration header (measured over all 157 recomp TUs: 0
# called-undeclared, 0 declared-uncalled): exactly the symbols the TU CALLS, defined there or
# not, in sorted order. A DECLARE for a symbol the TU only defines changes clang's output.
CALL = re.compile(r"\b(\w+)\(ctx, base\)")
BANNER = "// Generated by tools/organize_generated.py from rexglue codegen output - DO NOT EDIT\n"
# A codegen function identifier as a whole C token, optionally with the __imp__ prefix that
# DEFINE_REX_FUNC/DECLARE_REX_FUNC paste onto it (simde_mm_sub_ps and loc_ labels never match).
SUBSYM = re.compile(r"(?<![A-Za-z0-9_])(__imp__)?(sub_[0-9A-F]{8})(?![A-Za-z0-9_])")
WORD = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
CODEGEN_SUPPORT = ("init.h", "init.cpp", "register.cpp", "funcs.h")  # renamed copies (--ids pdb)


def rename_text(text: str, ren: dict) -> str:
    """Rewrite every sub_<ADDR> (and __imp__sub_<ADDR>) token that the map names; others stay."""
    if not ren:
        return text
    return SUBSYM.sub(lambda m: (m.group(1) or "") + ren.get(m.group(2), m.group(2)), text)


def build_rename(by: dict, reg: dict, blocks: dict, declared: set):
    """--ids pdb: codegen symbol -> PDB-derived identifier for every named, defined function.

    Scheme (docs/NAMED_TREE.md): the allocation/names ident minus its _<ADDR> suffix, i.e. the
    PDB qualified name with '::' -> '__' and every other non-identifier character -> '_'.
    The _<ADDR> suffix is kept (the ident is used whole) when
      (a) the PDB name is not class/namespace-qualified (no '::'): these are extern "C" names in
          the same link as the host CRT, Win32, SDL and the SDK, so a bare free-function name
          (memcpy, XamUserGetName, speex_bits_pack, ...) could bind to or override a host symbol;
      (b) the stripped name is shared by more than one function (overloads, folded copies,
          parent+offset pieces): every function of the collision keeps its address;
      (c) the stripped name, or its __imp__ form, equals any other codegen symbol.
    The result must be a C++ identifier, unique, never sub_<8 hex>, never start with __imp__,
    and neither it nor __imp__<it> may equal an existing codegen symbol; anything else refuses."""
    existing = set(declared) | set(blocks) | set(reg)
    cand = {}
    for sym in blocks:
        a = reg.get(sym)
        r = by.get(a) if a is not None else None
        if r is None or not r.get("ident") or sym != "sub_%08X" % a:
            continue
        ident = r["ident"]
        suffix = "_%08X" % a
        if not ident.endswith(suffix):
            raise Refused("ident %s of 0x%08X does not end in %s" % (ident, a, suffix))
        cand[sym] = (ident, ident[:-len(suffix)], "::" in r["pdb_name"])
    count = collections.Counter(base for _i, base, _q in cand.values())

    def clash(n):
        return n in existing or ("__imp__" + n) in existing or n.startswith("__imp__")

    ren, stats = {}, collections.Counter()
    for sym, (ident, base, qualified) in sorted(cand.items()):
        if not qualified:
            new, why = ident, "free_function_keeps_addr"
        elif count[base] > 1:
            new, why = ident, "collision_keeps_addr"
        elif clash(base) or not base:
            new, why = ident, "codegen_symbol_clash_keeps_addr"
        else:
            new, why = base, "bare_name"
        if not IDENT_OK.match(new) or re.fullmatch(r"sub_[0-9A-F]{8}", new) or clash(new):
            raise Refused("renamed identifier %r for %s is unusable" % (new, sym))
        ren[sym] = new
        stats[why] += 1
    if len(set(ren.values())) != len(ren):
        dup = [n for n, k in collections.Counter(ren.values()).items() if k > 1]
        raise Refused("renamed identifiers are not unique (first: %s)" % dup[:3])
    stats["collision_groups"] = sum(1 for b, k in count.items() if k > 1)
    return ren, dict(stats)


class Refused(Exception):
    pass


def parse_recomp(path: Path):
    """[(symbol, block_text)] with block_text = 'DEFINE_REX_FUNC(...) {\\n' ... '}\\n' verbatim."""
    lines = path.read_text(encoding="utf-8", newline="").splitlines(keepends=True)
    out, cur, name = [], None, None
    for n, line in enumerate(lines, 1):
        if cur is None:
            m = BEGIN.match(line.rstrip("\r\n"))
            if m:
                cur, name = [line], m.group(1)
            elif line.strip() and not line.startswith("#include "):
                raise Refused("%s:%d: top-level text outside a function block" % (path.name, n))
        else:
            cur.append(line)
            if line.rstrip("\r\n") == "}":
                out.append((name, "".join(cur)))
                cur = None
    if cur is not None:
        raise Refused("%s: unterminated block %s" % (path.name, name))
    return out


def read_generated(gen: Path):
    recomp = sorted(gen.glob(PROJECT + "_recomp.*.cpp"), key=lambda p: int(p.suffixes[-2][1:]))
    if not recomp:
        raise Refused("no %s_recomp.*.cpp in %s" % (PROJECT, gen))
    blocks, units = {}, []
    for p in recomp:
        text = p.read_text(encoding="utf-8", newline="")
        head = text[:text.index("DEFINE_REX_FUNC(")] if "DEFINE_REX_FUNC(" in text else text
        syms = []
        for sym, body in parse_recomp(p):
            if sym in blocks:
                raise Refused("symbol %s defined twice in app/generated" % sym)
            blocks[sym] = body
            syms.append(sym)
        units.append((int(p.suffixes[-2][1:]), head, syms))
    declared = set()
    for h in gen.glob(PROJECT + "_funcs*.h"):
        for line in h.read_text(encoding="utf-8").splitlines():
            m = DECL.match(line)
            if m:
                declared.add(m.group(1))
    reg = dict((s, int(a, 16)) for a, s in re.findall(
        r"SetFunction\(0x([0-9A-Fa-f]+), (\w+)\);", (gen / (PROJECT + "_register.cpp")).read_text(encoding="utf-8")))
    return recomp, blocks, declared, reg, units


def load_allocation(path: Path):
    with gzip.open(path, "rt", encoding="utf-8") as f:
        rows = list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))
    by = {}
    for r in rows:
        a = int(r["addr"], 16)
        if a in by:
            raise Refused("allocation table has address 0x%08X twice" % a)
        by[a] = r
    return by


IDENT_OK = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def apply_names(by: dict, path: Path) -> int:
    """config/names.tsv.gz (tools/pdbchain; name_pass.py is a deprecated wrapper): a PDB name for a row whose allocation
    has none. Refuses a row that already carries a name, an unknown address, a non-C++
    identifier or a duplicate address; the symbol and registration are untouched."""
    if not path.exists():
        return 0
    seen = set()
    with gzip.open(path, "rt", encoding="utf-8") as f:
        for n in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
            a = int(n["addr"], 16)
            r = by.get(a)
            if r is None or a in seen:
                raise Refused("names table: 0x%08X unknown or listed twice" % a)
            seen.add(a)
            if r["name_status"] != "NONE" and not (n["method"] == "N9" and r["name_status"].startswith("AMBIGUOUS")
                                                   and n.get("aliases")):
                raise Refused("names table: 0x%08X already named (%s)" % (a, r["name_status"]))
            if not IDENT_OK.match(n["ident"]):
                raise Refused("names table: 0x%08X ident %r is not a C++ identifier" % (a, n["ident"]))
            r["name_status"] = "NAME_" + n["method"]
            r["pdb_name"] = n["pdb_name"]
            r["basis"] += ";name=%s" % n["method"]
            r["aliases"] = n.get("aliases", "")
            r["ident"] = n["ident"] if r["symbol"] == "sub_%08X" % a else ""
    return len(seen)


def comment_for(r: dict, new: str | None = None) -> str:
    def clean(s):  # a backslash before a newline would splice the next line into the comment
        return s.replace("\n", " ").replace("\\", "/")
    head = "// %s  %s  [%s %s]" % (r["addr"], clean(r["pdb_name"]) or r["symbol"], r["class"], r["basis"])
    out = [head]
    if new:
        out.append("//   codegen symbol: %s (registered by address 0x%s)" % (r["symbol"], r["addr"][2:]))
    if r.get("aliases"):
        out.append("//   folded aliases: %s" % clean(r["aliases"]))
    if r["src_file"]:
        out.append("//   src: %s%s" % (clean(r["src_file"]), ":" + r["src_line"] if r["src_line"] else ""))
    if r["prototype"]:
        out.append("//   sig: %s" % clean(r["prototype"]))
    if r["calltype"]:
        out.append("//   pdb: cv=%s params=%s this=%s (guest PPC ABI unchanged)" % (r["calltype"], r["nparams"], r["has_this"]))
    return "\n".join(out) + "\n"


def build(gen: Path, alloc: Path, max_per_file: int, names: Path = REPO / "config" / "names.tsv.gz",
          ids: str = "pdb"):
    recomp, blocks, declared, reg, units = read_generated(gen)
    where = {s: (u, k) for u, _h, syms in units for k, s in enumerate(syms)}
    by = load_allocation(alloc)
    apply_names(by, names)
    ren, rstats = build_rename(by, reg, blocks, declared) if ids == "pdb" else ({}, {})

    def rn(t):
        return rename_text(t, ren)
    files = collections.defaultdict(list)
    undetermined = {}
    missing = []
    for sym in blocks:
        a = reg.get(sym)
        r = by.get(a) if a is not None else None
        if r is None:
            missing.append(sym)
            continue
        if r["symbol"] != sym:
            raise Refused("allocation row 0x%08X names %s, codegen names %s" % (a, r["symbol"], sym))
        if r["class"] == "UNDETERMINABLE":
            # no source file is provable (config/undeterminable.tsv): the body stays verbatim in
            # its codegen-order unit file, under its codegen TU -- no folder is invented
            undetermined[sym] = r
            continue
        files[r["tree_path"]].append((a, sym, r))
    if missing:
        raise Refused("%d defined functions have no allocation row (first: %s); rebuild the table"
                      % (len(missing), missing[:3]))
    out = {}
    manifest = []
    aliases = []
    file_of = {}
    for tree in sorted(files):
        items = sorted(files[tree])
        chunks = [items[i:i + max_per_file] for i in range(0, len(items), max_per_file)]
        for k, chunk in enumerate(chunks):
            rel = tree if len(chunks) == 1 else tree[:-4] + ".part%d.cpp" % k
            body = []
            for a, sym, r in chunk:
                u, k = where[sym]
                body.append(comment_for(r, ren.get(sym)))
                body.append("#if !defined(DS2_UNIT) || (DS2_UNIT == %d && DS2_LO <= %d && %d <= DS2_HI)\n" % (u, k, k))
                if r["ident"] and not ren:
                    body.append("#define %s %s\n" % (r["ident"], sym))
                    aliases.append((r["ident"], sym, r["addr"]))
                body.append(rn(blocks[sym]))
                body.append("#endif\n\n")
                manifest.append((r["addr"], sym, rel, r["class"]))
                file_of[sym] = rel
            text = "".join(body)
            # codegen's rule, on codegen's own symbols (the renamed text is not in `declared`)
            used = sorted(set(CALL.findall("".join(blocks[s] for _a, s, _r in chunk))) & declared)
            src = {r["src_file"] for _, _, r in chunk if r["src_file"]}
            hdr = [BANNER, "// Named tree: %s\n" % rel]
            for s in sorted(src)[:8]:
                hdr.append("// original source: %s\n" % s.replace("\\", "/"))
            hdr.append("// Compiled through _units/ (the codegen TU grouping, so clang sees the very\n"
                       "// same translation units); compiled alone, every block below is enabled.\n")
            hdr.append('\n#ifndef DS2_UNIT\n#include "%s_pch.h"\n\n' % PROJECT)
            hdr.extend("DECLARE_REX_FUNC(%s);\n" % u for u in sorted(rn(x) for x in used))
            hdr.append("#endif\n")
            out[rel] = "".join(hdr) + "\n" + text
    # units: codegen TU N, rebuilt from the named files in codegen order -- same declaration
    # header first line(s), same function order; every block selected exactly once
    unit_files = []
    for u, head, syms in units:
        lines = [head, BANNER, "#define DS2_UNIT %d\n" % u]
        k = 0
        while k < len(syms):
            if syms[k] in undetermined:
                r = undetermined[syms[k]]
                lines.append("// %s  UNDETERMINABLE (config/undeterminable.tsv): kept in its codegen unit\n%s"
                             % (r["addr"], rn(blocks[syms[k]])))
                k += 1
                continue
            j = k
            while (j + 1 < len(syms) and syms[j + 1] not in undetermined
                   and file_of[syms[j + 1]] == file_of[syms[k]]):
                j += 1
            lines.append('#define DS2_LO %d\n#define DS2_HI %d\n#include "../%s"\n#undef DS2_LO\n#undef DS2_HI\n'
                         % (k, j, file_of[syms[k]]))
            k = j + 1
        rel = "_units/%s_unit.%d.cpp" % (PROJECT, u)
        out[rel] = "".join(lines)
        unit_files.append(rel)
        if ren:
            # the unit's declaration header, renamed: the unit's first line includes it by a
            # quoted name, so this copy beside the unit wins over app/generated's
            hn = "%s_funcs.%d.h" % (PROJECT, u)
            out["_units/" + hn] = rn((gen / hn).read_text(encoding="utf-8", newline=""))
    if ren:
        # registration (by address), the mapping table and the full declaration surface,
        # renamed and compiled from here instead of app/generated
        for s in CODEGEN_SUPPORT:
            fn = "%s_%s" % (PROJECT, s)
            out[fn] = rn((gen / fn).read_text(encoding="utf-8", newline=""))
        names = [BANNER, "#pragma once\n// --ids pdb: every named function's codegen symbol is rewritten to its PDB-derived\n"
                 "// identifier throughout this tree (machine-readable: symbols.tsv). Registration is\n"
                 "// by address and unchanged. <address>  <identifier>  <- <codegen symbol>\n"]
        names += ["// 0x%08X  %s  <- %s\n" % (reg[s], n, s) for s, n in sorted(ren.items(), key=lambda x: x[1])]
        out["ds2_names.h"] = "".join(names)
        out["symbols.tsv"] = "addr\tcodegen_symbol\tsymbol\n" + "".join(
            "0x%08X\t%s\t%s\n" % (reg[s], s, ren.get(s, s)) for s in sorted(blocks, key=lambda x: reg[x]))
        local = "${CMAKE_CURRENT_LIST_DIR}/%s" % PROJECT
    else:
        names = [BANNER, "#pragma once\n// PDB-derived aliases: <ident> -> codegen symbol (same function, same address).\n"]
        names += ["#define %s %s  // %s\n" % x for x in sorted(aliases)]
        if len({x[0] for x in aliases}) != len(aliases):
            raise Refused("alias identifiers are not unique")
        out["ds2_names.h"] = "".join(names)
        local = "${CMAKE_CURRENT_LIST_DIR}/../generated/%s" % PROJECT
    srcs = ["# Generated by tools/organize_generated.py - DO NOT EDIT\nset(GENERATED_SOURCES\n",
            "    %s_init.cpp\n" % local,
            "    %s_register.cpp\n" % local]
    srcs += ["    ${CMAKE_CURRENT_LIST_DIR}/%s\n" % k for k in unit_files]
    srcs.append(")\n")
    out["sources.cmake"] = "".join(srcs)
    out["manifest.tsv"] = "addr\tsymbol\tfile\tclass\n" + "".join("\t".join(m) + "\n" for m in sorted(manifest))
    fp = (gen / "codegen.build.stamp").read_text(encoding="utf-8").strip()
    h = hashlib.sha256()
    for p in recomp:
        h.update(p.read_bytes())
    h.update(alloc.read_bytes())
    if ren:  # --ids sub keeps the previous fingerprint bytes exactly
        h.update(b"ids=pdb")
    out["source.fingerprint"] = fp + "\n"
    out["inputs.sha256"] = h.hexdigest() + "\n"
    # what each unit must resolve to: codegen TU N's functions in order, bodies through the map
    plan = [(u, head, [ren.get(s, s) for s in syms], [rn(blocks[s]) for s in syms]) for u, head, syms in units]
    return out, blocks, len(recomp), plan, ren, rstats


def write_tree(dst: Path, out: dict):
    changed = deleted = 0
    for rel, text in out.items():
        p = dst / rel
        data = text.encode("utf-8")
        if p.is_file() and p.read_bytes() == data:
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
        changed += 1
    keep = {str(Path(k)).lower() for k in out}
    for p in sorted(dst.rglob("*"), reverse=True):
        if p.is_file() and str(p.relative_to(dst)).lower() not in keep:
            p.unlink()
            deleted += 1
        elif p.is_dir() and not any(p.iterdir()):
            p.rmdir()
    return changed, deleted


INVSYM = re.compile(r"(?<![A-Za-z0-9_])(__imp__)?([A-Za-z_][A-Za-z0-9_]*)")


def unrename_text(text: str, inv: dict) -> str:
    """The inverse map, applied to EVERY identifier token (not only the ones the forward pass
    wrote): a renamed name that also occurred in codegen's own text would come back wrong."""
    if not inv:
        return text
    return INVSYM.sub(lambda m: (m.group(1) or "") + inv.get(m.group(2), m.group(2)), text)


def verify(dst: Path, blocks: dict, ren: dict | None = None) -> dict:
    """Each function exactly once (keyed by its codegen symbol); body == forward-renamed codegen
    body AND inverse-renamed body == codegen body byte for byte (bijection on the text)."""
    ren = ren or {}
    inv = {v: k for k, v in ren.items()}
    seen = collections.Counter()
    equal = roundtrip = 0
    for p in sorted(dst.rglob("*.cpp")):
        for sym, text in parse_recomp_named(p):
            old = inv.get(sym, sym)
            seen[old] += 1
            orig = blocks.get(old)
            equal += orig is not None and rename_text(orig, ren) == text
            roundtrip += orig is not None and unrename_text(text, inv) == orig
    once = sum(1 for v in seen.values() if v == 1)
    return {"generated_functions": len(blocks), "named_functions": sum(seen.values()),
            "exactly_once": once, "set_equal": set(seen) == set(blocks),
            "bodies_identical_modulo_rename": equal, "bodies_roundtrip_identical": roundtrip}


def declared_of(gen: Path) -> set:
    return read_generated(gen)[2]


def verify_headers(dst: Path, declared: set, ren: dict) -> dict:
    """Each named TU's standalone header (#ifndef DS2_UNIT) declares exactly the codegen-declared
    functions its text calls, read back from the written file under the names it uses."""
    inv = {v: k for k, v in ren.items()}
    ok = n = 0
    for p in sorted(dst.rglob("*.cpp")):
        rel = p.relative_to(dst).as_posix()
        if rel.startswith("_units/") or "/" not in rel:
            continue
        text = p.read_text(encoding="utf-8", newline="")
        head, _, rest = text.partition("#endif\n")
        have = set(re.findall(r"^DECLARE_REX_FUNC\((\w+)\);$", head, re.M))
        need = {c for c in CALL.findall(rest) if inv.get(c, c) in declared}
        n += 1
        ok += have == need
    return {"named_tus": n, "named_tu_headers_exact": ok}


def rename_controls(blocks: dict, ren: dict) -> dict:
    """Shake the body check on copies (in memory): it must pass the true rename, and fail a
    rename that misses one call target and one that swaps a call target for another name."""
    callers = [(s, b) for s, b in sorted(blocks.items())
               if any(t in ren and t != s for t in CALL.findall(b))]
    s, b = callers[0]
    tgt = next(t for t in CALL.findall(b) if t in ren and t != s)
    good = rename_text(b, ren)
    missed = rename_text(b, {k: v for k, v in ren.items() if k != tgt})
    other = next(v for k, v in sorted(ren.items()) if k != tgt and k != s)
    swapped = good.replace(ren[tgt] + "(ctx, base)", other + "(ctx, base)", 1)
    inv = {v: k for k, v in ren.items()}
    return {"control_function": s, "control_identity_equal": unrename_text(good, inv) == b,
            "control_missed_rename_detected": sum(1 for m in SUBSYM.finditer(missed) if m.group(2) in ren) > 0,
            "control_swapped_target_detected": unrename_text(swapped, inv) != b}


def verify_rename(dst: Path, gen: Path, ren: dict) -> dict:
    """--ids pdb only. (1) the renamed support files and unit declaration headers equal codegen's
    through the map and come back byte-identical through the inverse; (2) no token sub_<ADDR> of
    a renamed function is left on a non-comment line anywhere in the tree; (3) the registration
    table registers every address exactly as codegen did (address -> symbol through the map)."""
    inv = {v: k for k, v in ren.items()}
    files = ["%s_%s" % (PROJECT, s) for s in CODEGEN_SUPPORT]
    files += ["_units/" + p.name for p in sorted(gen.glob(PROJECT + "_funcs.*.h"))]
    support_ok = 0
    for rel in files:
        orig = (gen / Path(rel).name).read_text(encoding="utf-8", newline="")
        got = (dst / rel).read_text(encoding="utf-8", newline="") if (dst / rel).is_file() else None
        support_ok += got is not None and got == rename_text(orig, ren) and unrename_text(got, inv) == orig
    left = 0
    for p in dst.rglob("*"):
        if p.is_file() and p.suffix in (".cpp", ".h", ".cmake"):
            for line in p.read_text(encoding="utf-8", newline="").splitlines():
                if not line.lstrip().startswith("//"):
                    left += sum(1 for m in SUBSYM.finditer(line) if m.group(2) in ren)
    regx = re.compile(r"SetFunction\(0x([0-9A-Fa-f]+), (\w+)\);")
    a = regx.findall((gen / (PROJECT + "_register.cpp")).read_text(encoding="utf-8"))
    b = regx.findall((dst / (PROJECT + "_register.cpp")).read_text(encoding="utf-8"))
    reg_ok = len(a) == len(b) and all(x[0] == y[0] and ren.get(x[1], x[1]) == y[1] for x, y in zip(a, b))
    return {"renamed": len(ren), "support_files": len(files), "support_files_identical_modulo_rename": support_ok,
            "renamed_sub_tokens_left": left, "registration_entries": len(b),
            "registration_by_address_unchanged": reg_ok}


GUARD = re.compile(r"^#if !defined\(DS2_UNIT\) \|\| \(DS2_UNIT == (\d+) && DS2_LO <= (\d+) && \d+ <= DS2_HI\)$")


def verify_units(dst: Path, units: list) -> dict:
    """Resolve every _units file the way the preprocessor will (selector per block) and check
    that it yields codegen TU N's functions, in codegen's order, with byte-identical bodies."""
    cache = {}

    def guarded(rel):
        if rel not in cache:
            out, sel, cur = [], None, None
            for line in (dst / rel).read_text(encoding="utf-8", newline="").splitlines(keepends=True):
                m = GUARD.match(line.rstrip("\r\n"))
                if m:
                    sel = (int(m.group(1)), int(m.group(2)))
                    continue
                if cur is None:
                    b = BEGIN.match(line.rstrip("\r\n"))
                    if b:
                        cur = [b.group(1), [line], sel]
                else:
                    cur[1].append(line)
                    if line.rstrip("\r\n") == "}":
                        out.append((cur[0], "".join(cur[1]), cur[2]))
                        cur = None
            cache[rel] = out
        return cache[rel]

    ok_units = 0
    inc = re.compile(r'#define DS2_LO (\d+)\n#define DS2_HI (\d+)\n#include "\.\./([^"]+)"')
    for u, head, syms, bodies in units:
        text = (dst / ("_units/%s_unit.%d.cpp" % (PROJECT, u))).read_text(encoding="utf-8", newline="")
        got = []
        # walk the unit in order: an include contributes its selected blocks, an inline block
        # (UNDETERMINABLE) contributes itself
        pos = 0
        inline = list(parse_recomp_text(text))
        for m in re.finditer(r'#define DS2_LO (\d+)\n#define DS2_HI (\d+)\n#include "\.\./([^"]+)"|^DEFINE_REX_FUNC\((\w+)\) \{$',
                             text, re.M):
            if m.group(4):
                got.append(inline[pos])
                pos += 1
                continue
            lo, hi, rel = m.group(1), m.group(2), m.group(3)
            got += [(s, b) for s, b, sel in guarded(rel) if sel == (u, sel[1]) and int(lo) <= sel[1] <= int(hi)]
        ok_units += text.startswith(head) and got == list(zip(syms, bodies))
    return {"units": len(units), "units_resolving_to_codegen_tu": ok_units}


def parse_recomp_named(p: Path):
    """Named TUs also carry comments, #define and DECLARE lines at top level."""
    return parse_recomp_text(p.read_text(encoding="utf-8", newline=""))


def parse_recomp_text(text: str):
    lines = text.splitlines(keepends=True)
    out, cur, name = [], None, None
    for line in lines:
        if cur is None:
            m = BEGIN.match(line.rstrip("\r\n"))
            if m:
                cur, name = [line], m.group(1)
        else:
            cur.append(line)
            if line.rstrip("\r\n") == "}":
                out.append((name, "".join(cur)))
                cur = None
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--generated", default=str(APP / "generated"))
    ap.add_argument("--allocation", default=str(REPO / "config" / "allocation.tsv.gz"))
    ap.add_argument("--out", default=str(APP / "generated_named"))
    ap.add_argument("--names", default=str(REPO / "config" / "names.tsv.gz"),
                    help="pdbchain name table (absent: allocation names only)")
    ap.add_argument("--max-per-file", type=int, default=500)
    ap.add_argument("--verify", action="store_true", help="also check (a) (b) and re-run for (d)")
    ap.add_argument("--ids", choices=["pdb", "sub"], default="pdb",
                    help="pdb (default): rewrite named functions' sub_<ADDR> to PDB-derived identifiers "
                         "everywhere; sub: keep codegen symbols, emit #define aliases (previous behaviour)")
    a = ap.parse_args(argv)
    gen, dst = Path(a.generated), Path(a.out)
    try:
        out, blocks, ntu, plan, ren, rstats = build(gen, Path(a.allocation), a.max_per_file, Path(a.names), a.ids)
    except (Refused, OSError, KeyError) as exc:
        print("ORGANIZE REFUSED:", exc, file=sys.stderr)
        return 2
    changed, deleted = write_tree(dst, out)
    tus = sum(1 for k in out if k.endswith(".cpp") and "/" in k and not k.startswith("_units/"))
    print("organize: %d functions from %d codegen TUs -> %d named TUs; ids=%s renamed %d %s; "
          "%d files changed, %d deleted"
          % (len(blocks), ntu, tus, a.ids, len(ren), json.dumps(rstats, sort_keys=True), changed, deleted))
    if a.verify:
        v = verify(dst, blocks, ren)
        v.update(verify_units(dst, plan))
        v.update(verify_headers(dst, declared_of(gen), ren))
        if ren:
            v.update(verify_rename(dst, gen, ren))
            v.update(rename_controls(blocks, ren))
        out2 = build(gen, Path(a.allocation), a.max_per_file, Path(a.names), a.ids)[0]
        c2, d2 = write_tree(dst, out2)
        v["second_run_files_changed"] = c2 + d2
        print(json.dumps(v, indent=1))
        ok = (v["set_equal"] and v["exactly_once"] == v["generated_functions"] == v["named_functions"]
              and v["bodies_identical_modulo_rename"] == v["bodies_roundtrip_identical"] == v["generated_functions"]
              and c2 + d2 == 0 and v["named_tu_headers_exact"] == v["named_tus"] == tus
              and v["units_resolving_to_codegen_tu"] == v["units"] == ntu)
        if ren:
            ok = ok and (v["support_files_identical_modulo_rename"] == v["support_files"]
                         and v["renamed_sub_tokens_left"] == 0 and v["registration_by_address_unchanged"]
                         and v["control_missed_rename_detected"] and v["control_swapped_target_detected"]
                         and v["control_identity_equal"])
        if not ok:
            print("ORGANIZE VERIFY FAILED", file=sys.stderr)
            return 2
        print("ORGANIZE VERIFY PASS")
    print("ORGANIZE DONE", dst)
    return 0


if __name__ == "__main__":
    sys.exit(main())
